package com.multiforge.master;

import com.multiforge.protocol.ChunkKey;

import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.concurrent.CompletableFuture;
import java.util.concurrent.ConcurrentHashMap;
import java.util.concurrent.Executors;
import java.util.concurrent.ScheduledExecutorService;
import java.util.concurrent.TimeUnit;
import java.util.concurrent.atomic.AtomicLong;

/**
 * Grants at most one server the right to generate a never-seen chunk.
 *
 * <p>Without a lease, every server that loads a chunk the master has no data for
 * reaches the same {@code Optional.empty()} answer and starts world generation
 * locally. With several players spread over a cluster that easily means the same
 * chunk is generated on two or three machines at once: the duplicated work is
 * wasted CPU (the resource chunk loading is bound by) and the writes race, so the
 * last upload wins instead of one authoritative result. MultiPaper has the same
 * caveat; this class closes it server-side without changing the wire format.</p>
 *
 * <p>The lease is demand driven, so different chunks are generated by different
 * machines: the first server that needs a chunk generates it, and every other
 * server that needs the same chunk while generation is still running waits for
 * the generator's copy (through the normal peer read path) instead of generating
 * its own. The generator is normally the server whose player walked into the
 * chunk; when players are spread over the cluster, the generation and ticking
 * work is therefore spread as well.</p>
 *
 * <p>Waiting is deliberately bounded. A waiter stops waiting after
 * {@link #waitMillis()} and generates locally, because a stalled generator must
 * never keep a player's chunk load pending until the client-side IO timeout. A
 * lease that is not completed (generator crashed, chunk never loaded) is dropped
 * after {@link #leaseMillis()}, so the next reader can take over. Setting either
 * value to {@code 0} disables the feature and restores the old behaviour.</p>
 *
 * <p>Threading: all methods are safe to call from Netty handler threads, region
 * IO threads and the timer thread. State is kept in concurrent maps plus a
 * per-lease monitor that prevents a lost wakeup between "complete" and "add
 * waiter". Completing a lease never touches world state; it only completes
 * futures, and the read handler that owns the future re-enters the normal read
 * path.</p>
 */
public final class ChunkGenerationManager {

    /** What a reader should do after asking for the generation lease. */
    public enum Decision {
        /** No other server is generating the chunk: reply "empty" so vanilla generates. */
        GENERATE_LOCALLY,
        /** Another server finished (or gave up) generating: repeat the read. */
        RETRY_READ
    }

    /** Default lease lifetime; long enough for modded worldgen, short enough to recover. */
    private static final long DEFAULT_LEASE_MILLIS =
            Long.getLong("multiforge.master.generationLeaseMillis", 15_000L);
    /** Default time a reader waits for another server's generation before doing it itself. */
    private static final long DEFAULT_WAIT_MILLIS =
            Long.getLong("multiforge.master.generationWaitMillis", 2_000L);

    private static volatile long leaseMillis = DEFAULT_LEASE_MILLIS;
    private static volatile long waitMillis = DEFAULT_WAIT_MILLIS;

    private static final Map<ChunkKey, Lease> LEASES = new ConcurrentHashMap<>();
    private static final AtomicLong GRANTED = new AtomicLong();
    private static final AtomicLong WAITED = new AtomicLong();
    private static final AtomicLong TIMED_OUT = new AtomicLong();

    private static final ScheduledExecutorService TIMER =
            Executors.newSingleThreadScheduledExecutor(runnable -> {
                Thread thread = new Thread(runnable, "MultiForge-GenerationLease");
                thread.setDaemon(true);
                return thread;
            });

    private ChunkGenerationManager() {
    }

    /**
     * Applies the configured timings.
     *
     * <p>Called by {@link MultiForgeMaster#main(String[])} after the properties
     * file was read, and by tests that need short timeouts. Values are clamped to
     * zero (disabled) so a bad config cannot create a negative timeout.</p>
     *
     * @param newLeaseMillis how long a lease may stay incomplete, in milliseconds;
     *                       {@code 0} disables generation leases
     * @param newWaitMillis  how long a second reader waits for the generator before
     *                       generating itself, in milliseconds
     */
    public static void configure(long newLeaseMillis, long newWaitMillis) {
        leaseMillis = Math.max(0L, newLeaseMillis);
        waitMillis = Math.max(0L, newWaitMillis);
    }

    /** @return the effective lease lifetime in milliseconds, {@code 0} when disabled */
    public static long leaseMillis() {
        return leaseMillis;
    }

    /** @return how long a second reader waits for another server's generation */
    public static long waitMillis() {
        return waitMillis;
    }

    /**
     * Asks whether {@code connection} may generate a chunk, or must wait for the
     * server that is already generating it.
     *
     * <p>Called from {@code ReadChunkHandler} after the master found no stored
     * payload for the chunk. The returned future is completed exactly once:</p>
     * <ul>
     *   <li>immediately with {@link Decision#GENERATE_LOCALLY} when the caller got
     *       the lease (or leases are disabled);</li>
     *   <li>with {@link Decision#RETRY_READ} when the generator reported the chunk
     *       as loaded, saved it, or disconnected;</li>
     *   <li>with {@link Decision#GENERATE_LOCALLY} when the wait budget
     *       ({@link #waitMillis()}) expires, so the caller is never stuck.</li>
     * </ul>
     *
     * @param connection requesting server
     * @param world      logical world name
     * @param cx         chunk X
     * @param cz         chunk Z
     * @return future with the decision for this reader
     */
    public static CompletableFuture<Decision> acquire(ServerConnection connection, String world, int cx, int cz) {
        if (leaseMillis <= 0L) {
            return CompletableFuture.completedFuture(Decision.GENERATE_LOCALLY);
        }

        ChunkKey key = new ChunkKey(world, cx, cz);
        while (true) {
            Lease lease = LEASES.get(key);
            if (lease == null) {
                Lease created = new Lease(connection);
                if (LEASES.putIfAbsent(key, created) == null) {
                    GRANTED.incrementAndGet();
                    scheduleExpiry(key, created);
                    return CompletableFuture.completedFuture(Decision.GENERATE_LOCALLY);
                }
                continue;
            }

            if (lease.generator == connection) {
                // The same server asked twice (for example a retried read): it is
                // already the generator, so it must not wait for itself.
                return CompletableFuture.completedFuture(Decision.GENERATE_LOCALLY);
            }

            CompletableFuture<Decision> waiter = new CompletableFuture<>();
            if (!lease.addWaiter(connection, waiter)) {
                // The lease completed between the lookup and addWaiter; look again.
                continue;
            }
            WAITED.incrementAndGet();
            scheduleWaitTimeout(lease, waiter);
            return waiter;
        }
    }

    /**
     * Returns a wait handle when another server is currently generating the
     * chunk, or an empty optional when the normal read path may run.
     *
     * <p>Used as the first step of a region read: while a lease exists, the
     * generator is only a <em>subscriber</em> (its first read subscribed it), so
     * redirecting to it would ask a server that does not have the chunk yet, and
     * reading the master copy would return empty and start a duplicate
     * generation. Waiting is the only correct answer.</p>
     *
     * @param connection server that wants the chunk
     * @param world      logical world name
     * @param cx         chunk X
     * @param cz         chunk Z
     * @return a future completed with the same decisions as
     *         {@link #acquire(ServerConnection, String, int, int)}, or empty when
     *         this server may proceed with the normal read
     */
    public static Optional<CompletableFuture<Decision>> waitForCurrentGeneration(
            ServerConnection connection, String world, int cx, int cz) {
        if (leaseMillis <= 0L) {
            return Optional.empty();
        }
        ChunkKey key = new ChunkKey(world, cx, cz);
        while (true) {
            Lease lease = LEASES.get(key);
            if (lease == null || lease.generator == connection) {
                return Optional.empty();
            }
            CompletableFuture<Decision> waiter = new CompletableFuture<>();
            if (!lease.addWaiter(connection, waiter)) {
                continue;
            }
            WAITED.incrementAndGet();
            scheduleWaitTimeout(lease, waiter);
            return Optional.of(waiter);
        }
    }

    /**
     * Marks a chunk's generation as finished and wakes every waiting reader.
     *
     * <p>Called when a server subscribes the chunk (it now has an in-memory copy
     * peers can read), reports it as loaded, uploads it, or when the lease owner
     * disconnects. Passing a non-{@code null} {@code generator} only completes the
     * lease when that server is the one that holds it, so an unrelated server
     * subscribing the chunk cannot cut another server's generation short.</p>
     *
     * @param world     logical world name
     * @param cx        chunk X
     * @param cz        chunk Z
     * @param generator server that finished generating, or {@code null} when a
     *                  stored copy exists and any lease is obsolete
     */
    public static void complete(String world, int cx, int cz, ServerConnection generator) {
        ChunkKey key = new ChunkKey(world, cx, cz);
        Lease lease = LEASES.get(key);
        if (lease == null) {
            return;
        }
        if (generator != null && lease.generator != generator) {
            return;
        }
        if (LEASES.remove(key, lease)) {
            lease.finish();
        }
    }

    /**
     * Drops every lease and waiter belonging to a server that disconnected.
     *
     * <p>Waiters must be retried rather than abandoned: after the generator is
     * gone the chunk has to be generated somewhere else. Call this after the
     * subscription state of the connection was cleaned up so the retried read
     * does not get redirected to the departed server.</p>
     *
     * @param connection server that went away
     */
    public static void forget(ServerConnection connection) {
        for (Map.Entry<ChunkKey, Lease> entry : LEASES.entrySet()) {
            Lease lease = entry.getValue();
            if (lease.generator == connection) {
                if (LEASES.remove(entry.getKey(), lease)) {
                    lease.finish();
                }
            } else {
                lease.removeWaiter(connection);
            }
        }
    }

    /** @return number of chunks currently leased for generation */
    public static int activeLeaseCount() {
        return LEASES.size();
    }

    /** @return number of leases granted since the master started */
    public static long grantedCount() {
        return GRANTED.get();
    }

    /** @return number of reads that waited for another server's generation */
    public static long waitedCount() {
        return WAITED.get();
    }

    /** @return number of waits that hit the timeout and generated locally */
    public static long timeoutCount() {
        return TIMED_OUT.get();
    }

    /** Forgets every lease. Used when the master stops and by tests. */
    public static void clear() {
        for (Lease lease : LEASES.values()) {
            lease.finish();
        }
        LEASES.clear();
    }

    private static void scheduleExpiry(ChunkKey key, Lease lease) {
        long ttl = leaseMillis;
        if (ttl <= 0L) {
            return;
        }
        TIMER.schedule(() -> {
            if (LEASES.remove(key, lease)) {
                lease.finish();
            }
        }, ttl, TimeUnit.MILLISECONDS);
    }

    private static void scheduleWaitTimeout(Lease lease, CompletableFuture<Decision> waiter) {
        long budget = waitMillis;
        if (budget <= 0L) {
            // A zero wait budget means "never wait"; the caller generates now.
            if (lease.completeWaiter(waiter, Decision.GENERATE_LOCALLY)) {
                TIMED_OUT.incrementAndGet();
            }
            lease.removeWaiter(waiter);
            return;
        }
        TIMER.schedule(() -> {
            if (lease.completeWaiter(waiter, Decision.GENERATE_LOCALLY)) {
                TIMED_OUT.incrementAndGet();
            }
            lease.removeWaiter(waiter);
        }, budget, TimeUnit.MILLISECONDS);
    }

    /**
     * One generation lease: the server that is allowed to generate plus the
     * readers that wait for it.
     *
     * <p>The monitor guards {@link #waiters} and {@link #finished} so a waiter is
     * either added before completion or completed immediately, never lost.</p>
     */
    private static final class Lease {

        private final ServerConnection generator;
        private final Map<ServerConnection, CompletableFuture<Decision>> waiters = new HashMap<>();
        private boolean finished;

        private Lease(ServerConnection generator) {
            this.generator = generator;
        }

        private synchronized boolean addWaiter(ServerConnection connection,
                                               CompletableFuture<Decision> waiter) {
            if (finished) {
                return false;
            }
            waiters.putIfAbsent(connection, waiter);
            return true;
        }

        private synchronized void removeWaiter(ServerConnection connection) {
            waiters.remove(connection);
        }

        private synchronized void removeWaiter(CompletableFuture<Decision> waiter) {
            waiters.values().remove(waiter);
        }

        private synchronized boolean completeWaiter(CompletableFuture<Decision> waiter, Decision decision) {
            return waiter.complete(decision);
        }

        private void finish() {
            List<CompletableFuture<Decision>> toWake;
            synchronized (this) {
                finished = true;
                toWake = new ArrayList<>(waiters.values());
                waiters.clear();
            }
            for (CompletableFuture<Decision> waiter : toWake) {
                waiter.complete(Decision.RETRY_READ);
            }
        }
    }
}

