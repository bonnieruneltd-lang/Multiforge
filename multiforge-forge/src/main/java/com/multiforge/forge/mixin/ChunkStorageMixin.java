package com.multiforge.forge.mixin;

import com.multiforge.forge.MultiForgeServer;
import com.multiforge.forge.chunk.ChunkStorageRegistry;
import com.multiforge.forge.common.ChunkStore;
import com.mojang.datafixers.DataFixer;
import net.minecraft.nbt.CompoundTag;
import net.minecraft.world.level.ChunkPos;
import net.minecraft.world.level.chunk.storage.ChunkStorage;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfoReturnable;

import java.nio.file.Path;
import java.util.Optional;
import java.util.concurrent.CompletableFuture;

/**
 * Redirects vanilla chunk IO to the MultiForge cluster.
 *
 * <p>This is the direct replacement for MultiPaper's
 * {@code RegionFileIOThread} patches. In 1.20.1 every chunk read and write -
 * including the entity and poi storages and the {@code ChunkMap} itself, which
 * extends {@code ChunkStorage} - passes through these two methods, so no other IO
 * hook is required.</p>
 *
 * <p>The constructor injection only records the directory so
 * {@link ChunkStorageRegistry} can map a storage instance to its logical world and
 * storage type.</p>
 *
 * <p>Refmap: {@code multiforge.refmap.json} is generated by the Mixin annotation
 * processor and remaps these named members to SRG for production.</p>
 */
@Mixin(ChunkStorage.class)
public abstract class ChunkStorageMixin {

    /**
     * Captures the storage directory.
     *
     * @param path        directory of this storage
     * @param fixerUpper  data fixer (unused)
     * @param syncWrites  whether writes are synchronous (unused)
     * @param callbackInfo mixin callback
     */
    @Inject(method = "<init>", at = @At("RETURN"))
    private void multiforge$capturePath(Path path, DataFixer fixerUpper, boolean syncWrites, CallbackInfo callbackInfo) {
        ChunkStorageRegistry.capturePath((ChunkStorage) (Object) this, path);
    }

    /**
     * Replaces the read with a cluster read when MultiForge is active and the
     * storage belongs to a managed world.
     *
     * @param pos           chunk position
     * @param callbackInfo  mixin callback carrying the future
     */
    @Inject(method = "read", at = @At("HEAD"), cancellable = true)
    private void multiforge$read(ChunkPos pos, CallbackInfoReturnable<CompletableFuture<Optional<CompoundTag>>> callbackInfo) {
        MultiForgeServer server = MultiForgeServer.instanceOrNull();
        if (server == null) {
            return;
        }
        ChunkStore store = ChunkStorageRegistry.resolve((ChunkStorage) (Object) this);
        if (store == null || !server.chunkIo().shouldIntercept(store)) {
            return;
        }
        callbackInfo.setReturnValue(server.chunkIo().read(store, pos));
    }

    /**
     * Replaces the write with a cluster upload when MultiForge is active and the
     * storage belongs to a managed world.
     *
     * @param pos          chunk position
     * @param tag          chunk NBT
     * @param callbackInfo mixin callback
     */
    @Inject(method = "write", at = @At("HEAD"), cancellable = true)
    private void multiforge$write(ChunkPos pos, CompoundTag tag, CallbackInfo callbackInfo) {
        MultiForgeServer server = MultiForgeServer.instanceOrNull();
        if (server == null) {
            return;
        }
        ChunkStore store = ChunkStorageRegistry.resolve((ChunkStorage) (Object) this);
        if (store == null || !server.chunkIo().shouldIntercept(store)) {
            return;
        }
        server.chunkIo().write(store, pos, tag);
        callbackInfo.cancel();
    }
}
